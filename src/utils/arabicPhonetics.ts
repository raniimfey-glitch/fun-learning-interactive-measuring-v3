/**
 * Converts a raw capacity number (in ml or L) to vocalized Arabic words
 */
export function numberToVocalizedArabic(num: number, unitType: 'ml' | 'L' = 'ml'): string {
  if (unitType === 'L') {
    if (num === 1) return "لِتْرٌ وَاحِدٌ";
    if (num === 2) return "لِتْرَانِ اثْنَانِ";
    if (num === 0.5) return "نِصْفُ لِتْرٍ";
    if (num === 0.25) return "رُبْعُ لِتْرٍ";
    if (num === 0.75) return "ثَلَاثَةُ أَرْبَاعِ اللِّتْرِ";
    return `${num} لِتْرَاتٍ`;
  }

  // ml numbers
  switch (num) {
    case 1000:
      return "أَلْفُ مِيلِيلِتْرٍ";
    case 2000:
      return "أَلْفَا مِيلِيلِتْرٍ";
    case 500:
      return "خَمْسُمِائَةِ مِيلِيلِتْرٍ";
    case 250:
      return "مِائَتَانِ وَخَمْسُونَ مِيلِيلِتْرًا";
    case 750:
      return "سَبْعُمِائَةٍ وَخَمْسُونَ مِيلِيلِتْرًا";
    case 100:
      return "مِائَةُ مِيلِيلِتْرٍ";
    case 200:
      return "مِائَتَا مِيلِيلِتْرٍ";
    case 300:
      return "ثَلَاثُمِائَةِ مِيلِيلِتْرٍ";
    case 400:
      return "أَرْبَعُمِائَةِ مِيلِيلِتْرٍ";
    case 470:
      return "أَرْبَعُمِائَةٍ وَسَبْعُونَ مِيلِيلِتْرًا";
    case 530:
      return "خَمْسُمِائَةٍ وَثَلَاثُونَ مِيلِيلِتْرًا";
    case 600:
      return "سِتُّمِائَةِ مِيلِيلِتْرٍ";
    case 800:
      return "ثَمَانُمِائَةِ مِيلِيلِتْرٍ";
    case 900:
      return "تِسْعُمِائَةِ مِيلِيلِتْرٍ";
    default:
      return `${num} مِيلِيلِتْرًا`;
  }
}

/**
 * Cleans text from emojis and replaces math symbols/fractions with phonetically vocalized Arabic
 */
export function prepareForSpeech(text: string): string {
  if (!text) return "";

  let res = text;

  // 1. Remove all emojis & decoration symbols
  res = res.replace(/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{1F900}-\u{1F9FF}\u{1F600}-\u{1F64F}\u{1F680}-\u{1F6FF}]/gu, '');
  res = res.replace(/[🪣🥛🥤🏺⚖️💧🌊💦🌟⭐🏆👍💪❌✅🔄➡️🔍🫗🖊️💡✕]/gu, '');

  // 2. Normalize zero/one ألف mistakes explicitly
  res = res.replace(/(?:صِفْرٌ?|صِفْر|صفر)\s*(?:أَلْفٌ?|أَلْف|ألف)/gu, 'أَلْف');
  res = res.replace(/(?:وَاحِدٌ?|وَاحِد|واحد)\s*(?:أَلْفٌ?|أَلْف|ألف)/gu, 'أَلْف');

  // 3. Convert numbers with units first (longest/most specific matches)
  res = res.replace(/(?<!\d)1000\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'أَلْفُ مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)2000\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'أَلْفَا مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)500\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'خَمْسُمِائَةِ مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)250\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'مِائَتَانِ وَخَمْسُونَ مِيلِيلِتْرًا');
  res = res.replace(/(?<!\d)750\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'سَبْعُمِائَةٍ وَخَمْسُونَ مِيلِيلِتْرًا');
  res = res.replace(/(?<!\d)100\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'مِائَةُ مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)200\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'مِائَتَا مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)300\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'ثَلَاثُمِائَةِ مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)400\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'أَرْبَعُمِائَةِ مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)470\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'أَرْبَعُمِائَةٍ وَسَبْعُونَ مِيلِيلِتْرًا');
  res = res.replace(/(?<!\d)530\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'خَمْسُمِائَةٍ وَثَلَاثُونَ مِيلِيلِتْرًا');
  res = res.replace(/(?<!\d)600\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'سِتُّمِائَةِ مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)800\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'ثَمَانُمِائَةِ مِيلِيلِتْرٍ');
  res = res.replace(/(?<!\d)900\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'تِسْعُمِائَةِ مِيلِيلِتْرٍ');

  // Unknown quantity + unit
  res = res.replace(/_{2,}\s*(?:مِيلِيلِتْرٍ?|مِيلِيلِتْرًا?|مليلتر(?:ا|ًا)?|ميليلتر(?:ا|ًا)?|مل)(?!\p{L})/gu, 'كَمْ مِيلِيلِتْرًا');
  res = res.replace(/_{2,}\s*(?:لِتْرٍ?|لِتْرًا?|لتر(?:ا|ًا)?|ل)(?!\p{L})/gu, 'كَمْ لِتْرًا');
  res = res.replace(/_{2,}/gu, ' كَمْ ');

  // Liters
  res = res.replace(/(?<!\d)1\s*(?:لِتْرٍ?|لِتْرًا?|لتر(?:ا|ًا)?|ل)(?!\p{L})/gu, 'لِتْرٌ وَاحِدٌ');
  res = res.replace(/(?<!\d)2\s*(?:لِتْرَيْنِ?|لِتْرَانِ?|لترين|لتران|ل)(?!\p{L})/gu, 'لِتْرَانِ اثْنَانِ');

  // Fractions with Liters
  res = res.replace(/½\s*(?:لِتْرٍ?|لتر|ل)?/gu, 'نِصْفُ لِتْرٍ');
  res = res.replace(/¼\s*(?:لِتْرٍ?|لتر|ل)?/gu, 'رُبْعُ لِتْرٍ');
  res = res.replace(/¾\s*(?:لِتْرٍ?|لتر|ل)?/gu, 'ثَلَاثَةُ أَرْبَاعِ اللِّتْرِ');

  // Standalone multi-digit numbers (guaranteeing 1000 = أَلْفٌ)
  res = res.replace(/(?<!\d)1000(?!\d)/gu, 'أَلْفٌ');
  res = res.replace(/(?<!\d)2000(?!\d)/gu, 'أَلْفَانِ');
  res = res.replace(/(?<!\d)500(?!\d)/gu, 'خَمْسُمِائَةٍ');
  res = res.replace(/(?<!\d)250(?!\d)/gu, 'مِائَتَانِ وَخَمْسُونَ');
  res = res.replace(/(?<!\d)750(?!\d)/gu, 'سَبْعُمِائَةٍ وَخَمْسُونَ');
  res = res.replace(/(?<!\d)100(?!\d)/gu, 'مِائَةٌ');
  res = res.replace(/(?<!\d)200(?!\d)/gu, 'مِائَتَانِ');
  res = res.replace(/(?<!\d)300(?!\d)/gu, 'ثَلَاثُمِائَةٍ');
  res = res.replace(/(?<!\d)400(?!\d)/gu, 'أَرْبَعُمِائَةٍ');
  res = res.replace(/(?<!\d)470(?!\d)/gu, 'أَرْبَعُمِائَةٍ وَسَبْعُونَ');
  res = res.replace(/(?<!\d)530(?!\d)/gu, 'خَمْسُمِائَةٍ وَثَلَاثُونَ');
  res = res.replace(/(?<!\d)600(?!\d)/gu, 'سِتُّمِائَةٍ');
  res = res.replace(/(?<!\d)800(?!\d)/gu, 'ثَمَانُمِائَةٍ');
  res = res.replace(/(?<!\d)900(?!\d)/gu, 'تِسْعُمِائَةٍ');

  // Single digits
  res = res.replace(/(?<!\d)0(?!\d)/gu, 'صِفْرٌ');
  res = res.replace(/(?<!\d)1(?!\d)/gu, 'وَاحِدٌ');
  res = res.replace(/(?<!\d)2(?!\d)/gu, 'اثْنَانِ');
  res = res.replace(/(?<!\d)3(?!\d)/gu, 'ثَلَاثَةٌ');
  res = res.replace(/(?<!\d)4(?!\d)/gu, 'أَرْبَعَةٌ');
  res = res.replace(/(?<!\d)6(?!\d)/gu, 'سِتَّةٌ');

  // Direct phrase replacements (ordered by length descending)
  for (const [key, val] of PHONETIC_PHRASES) {
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    res = res.replace(new RegExp(escaped, 'g'), val);
  }

  // Math operators
  res = res.replace(/\+/gu, ' زَائِد ');
  res = res.replace(/[−-]/gu, ' نَاقِص ');
  res = res.replace(/[×*]/gu, ' ضَرْب ');
  res = res.replace(/[÷/]/gu, ' تَقْسِيم ');
  res = res.replace(/=/gu, ' يُسَاوِي ');
  res = res.replace(/؟/gu, ' ؟ ');

  // Final safety pass for "صفر ألف" or "واحد ألف"
  res = res.replace(/(?:صِفْرٌ?|صِفْر|صفر)\s*(?:أَلْفٌ?|أَلْف|ألف)/gu, 'أَلْف');
  res = res.replace(/(?:وَاحِدٌ?|وَاحِد|واحد)\s*(?:أَلْفٌ?|أَلْف|ألف)/gu, 'أَلْف');

  // Clean double spaces
  res = res.replace(/\s{2,}/g, ' ').trim();

  return res;
}
